"""Driver registration and lookup.

Built-in drivers register themselves with `@register_driver(kind, type)`
at import time (see the bottom of e.g. drivers/tuya/cover.py). A
config.yaml entry like `{kind: cover, type: tuya_curtain_switch, ...}` is
resolved back to that factory here.

To add a new driver you do not edit this file at all: drop a new module
under `localhome/drivers/`, decorate its factory function, and reference
its `type` name from config.yaml - `load_builtin_drivers()` below
discovers it automatically by walking the drivers package.
"""
from __future__ import annotations

import importlib
import logging
import pkgutil
from typing import Any, Callable

logger = logging.getLogger(__name__)

_FACTORIES: dict[tuple[str, str], Callable[[dict], Any]] = {}
_loaded = False
# driver module -> the top-level package its import was missing, for the
# admin panel's system status and `localhome-cli doctor` - a skipped
# module otherwise only shows up as one warning line in the startup log.
_SKIPPED: dict[str, str] = {}
# Missing package -> optional extra that installs it (if any), so the
# remedy shown is the project's own install command, not a bare pip name.
_EXTRA_FOR_PACKAGE: dict[str, str] = {}


def register_driver(kind: str, type_name: str):
    """Class/function decorator: register a driver factory for `kind`/`type_name`."""

    def decorator(factory):
        key = (kind, type_name)
        if key in _FACTORIES:
            raise ValueError(f"Duplicate driver registration for {key!r}")
        _FACTORIES[key] = factory
        return factory

    return decorator


# Every module under localhome.drivers. From source they're found by
# walking the folders; a binary compiled by Nuitka (the .deb) has none to
# walk, so this list says them - tests/test_registry_modules.py keeps it
# the same as the folders.
BUILTIN_DRIVER_MODULES = (
    "localhome.drivers.ewelink.cloud",
    "localhome.drivers.ewelink.power",
    "localhome.drivers.manual.climate",
    "localhome.drivers.meross.plug",
    "localhome.drivers.mqtt.base",
    "localhome.drivers.mqtt.client",
    "localhome.drivers.mqtt.cover",
    "localhome.drivers.mqtt.number",
    "localhome.drivers.mqtt.paths",
    "localhome.drivers.mqtt.rpc",
    "localhome.drivers.mqtt.sensor",
    "localhome.drivers.mqtt.shelly_light",
    "localhome.drivers.mqtt.state_cache",
    "localhome.drivers.mqtt.switch",
    "localhome.drivers.notifiers.telegram",
    "localhome.drivers.simulated.climate",
    "localhome.drivers.simulated.number",
    "localhome.drivers.simulated.switch",
    "localhome.drivers.simulated.world",
    "localhome.drivers.tuya.air_quality",
    "localhome.drivers.tuya.client",
    "localhome.drivers.tuya.cover",
)


def load_builtin_drivers() -> None:
    """Import every module under localhome.drivers so its @register_driver
    calls run. Safe to call more than once.

    A module whose own third-party SDK isn't installed is logged and skipped
    rather than aborting startup entirely - the same "one broken thing shouldn't
    take down everything else" rule the rest of this app follows, just
    applied one import earlier than DeviceManager's own per-integration
    try/except.
    """
    global _loaded
    if _loaded:
        return
    _loaded = True
    import localhome.drivers as drivers_pkg

    module_names = set(BUILTIN_DRIVER_MODULES)
    try:
        for module_info in pkgutil.walk_packages(drivers_pkg.__path__, prefix="localhome.drivers."):
            module_names.add(module_info.name)
    except (OSError, AttributeError):
        pass

    for mod_name in sorted(module_names):
        try:
            importlib.import_module(mod_name)
        except ImportError as exc:
            missing = (exc.name or "?").split(".")[0]
            _SKIPPED[mod_name] = missing
            logger.warning(
                "Skipping driver module %s - package %r isn't installed "
                "(if this is a driver you need: %s)",
                mod_name,
                missing,
                install_hint(missing),
            )


def install_hint(package: str) -> str:
    extra = _EXTRA_FOR_PACKAGE.get(package)
    return f"pip install -e .[{extra}]" if extra else f"pip install {package}"


def skipped_driver_modules() -> list[dict]:
    """Driver modules that couldn't be imported, each with the package
    it was missing and the command that installs it."""
    load_builtin_drivers()
    return [
        {"module": module, "missing_package": package, "install": install_hint(package)}
        for module, package in sorted(_SKIPPED.items())
    ]


def create(kind: str, type_name: str, options: dict) -> list:
    """Instantiate the driver(s) for one config.yaml integration entry.

    A factory may return a single driver or a list - Tuya drivers fan out
    one instance per matching entry in their devices_file, since one LAN
    scan/wizard dump commonly holds several physical devices of the same
    kind (e.g. five roller shutters).
    """
    load_builtin_drivers()
    key = (kind, type_name)
    factory = _FACTORIES.get(key)
    if factory is None:
        available = sorted(f"{k}/{t}" for k, t in _FACTORIES)
        message = f"No driver registered for kind={kind!r} type={type_name!r}."
        if _SKIPPED:
            # The likeliest cause by far: the driver exists but its
            # optional package isn't installed. Say so before the list.
            skipped = ", ".join(f"{m} (needs: {install_hint(p)})" for m, p in sorted(_SKIPPED.items()))
            message += f" Driver modules skipped for a missing package: {skipped}."
        raise ValueError(f"{message} Available kind/type combinations: {available}")
    result = factory(options)
    return result if isinstance(result, list) else [result]


def known_drivers() -> list[tuple[str, str]]:
    load_builtin_drivers()
    return sorted(_FACTORIES)
